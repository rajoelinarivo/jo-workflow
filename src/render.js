// Renders the neutral harness into the files each system reads.
// Returns { files: [{ path, content }], merges: [{ path, apply }], warnings: [] }.
// `files` are owned by the generator (hash-tracked); `merges` patch shared JSON
// files the dev may also edit (only generator-managed entries are replaced).
import fs from "node:fs";
import path from "node:path";
import { read, walk, frontmatter, renderPlaceholders, json } from "./util.js";
import { GENERATOR_ROOT, DESCRIPTION } from "./project.js";

const SIGNED = `jo-workflow (${DESCRIPTION})`;
const BANNER_MD = `<!-- Generated by ${SIGNED} from .jow/ - do not edit. Change .jow/ then run: jo-workflow sync -->\n`;
const BRIDGE = ".jow/runtime/bridge.mjs";
// Hook entries pointing at the bridge, including the pre-0.3 .harness/ location.
const BRIDGE_RE = /\.(jow|harness)\/runtime\/bridge\.mjs/;

const firstSentence = (s) => {
  const first = String(s || "").split(/(?<=\.)\s/)[0];
  return first.length > 160 ? first.slice(0, 157).replace(/\s+\S*$/, "") + "..." : first;
};
const byOrder = (a, b) => (a.data.order ?? 100) - (b.data.order ?? 100) || a.name.localeCompare(b.name);

// ---------------------------------------------------------------- instructions

const AUTONOMY_TEXT = {
  guided: "stop for approval at the phases marked [gate]",
  step: "stop for approval after every phase",
  auto: "stop only when blocked or a decision is needed",
};

/** Placeholders computed from the harness itself, on top of commands and project name. */
export function extraPlaceholders(manifest, items) {
  const workflows = items.workflow.map((w) => `| \`${w.name}\` | ${String(w.data.description || "").replace(/\|/g, "\\|")} |`);
  return {
    "harness.workflows": workflows.length ? ["| Workflow | Use it for |", "|---|---|", ...workflows].join("\n") : "(no workflow installed)",
    "orchestrator.autonomy": manifest.orchestrator.autonomy,
    "orchestrator.trigger": manifest.orchestrator.trigger,
  };
}

function instructions(manifest, items, systems) {
  const ph = (t) => renderPlaceholders(t, manifest);
  const memory = [...items.memory].sort(byOrder);
  const out = [BANNER_MD];
  if (items.skill.some((s) => s.name === "dev")) {
    const { trigger, autonomy } = manifest.orchestrator;
    out.push(
      "## Entry point: the dev orchestrator",
      "",
      "- `/dev <request>` (Codex: `$dev <request>`) runs the whole workflow for a task: classify, plan, implement, verify, review, remember. `/dev` alone resumes the task in progress.",
      trigger === "auto"
        ? "- For any development request that does not explicitly name a skill, command or subagent, follow the `dev` skill even if the user did not type `/dev`. Answer plain questions directly."
        : "- Use the `dev` skill only when the user asks for it.",
      "- When the user invokes a specific skill, command or subagent directly, do only that: no orchestration.",
      `- Autonomy: \`${autonomy}\` (${AUTONOMY_TEXT[autonomy] || autonomy}). Tasks are tracked in \`.jow/work/\`: resume them instead of starting over.`,
      ""
    );
  }
  for (const m of memory.filter((m) => m.data.load !== "reference")) out.push(ph(m.body).trim(), "");
  const refs = memory.filter((m) => m.data.load === "reference");
  if (refs.length) {
    out.push("## Reference memory", "", "Read these files when the task touches their topic:", "");
    for (const m of refs) out.push(`- [${m.data.title || m.name}](.jow/memory/${m.name}.md)`);
    out.push("");
  }
  if (items.workflow.length) {
    out.push("## Workflows", "", "Used by the `dev` orchestrator; definitions in `.jow/workflows/`:", "");
    for (const w of items.workflow) out.push(`- \`${w.name}\` - ${firstSentence(w.data.description)}`);
    out.push("");
  }
  if (items.skill.length) {
    out.push("## Skills", "", "Load the matching skill before starting a task of that kind:", "");
    for (const s of items.skill) out.push(`- \`${s.name}\` - ${firstSentence(s.data.description)}`);
    out.push("");
  }
  if (items.agent.length) {
    out.push("## Subagents", "");
    for (const a of items.agent) out.push(`- \`${a.name}\` - ${firstSentence(a.data.description)}`);
    out.push("");
  }
  if (items.loop.length) {
    out.push("## Loops", "", "Run from a terminal: `jo-workflow loop <name>`", "");
    for (const l of items.loop) out.push(`- \`${l.name}\` - ${firstSentence(l.data.description)}`);
    out.push("");
  }
  out.push(
    "## Harness",
    "",
    `This agent harness is generated for: ${systems.join(", ")}. The source of truth is \`.jow/\`.`,
    "- Never edit generated files (`CLAUDE.md`, `AGENTS.md`, `.claude/`, `.agents/`, `.opencode/`, `.codex/`): edit `.jow/` then run `jo-workflow sync`.",
    "- Record durable decisions in `.jow/memory/decisions.md` and lessons learned in `.jow/memory/lessons.md`.",
    ""
  );
  return out.join("\n");
}

// ---------------------------------------------------------------- skills

// `source` tells `adopt` which neutral file a generated file comes from.
function skillFiles(skill, manifest, dir, data, flavor) {
  const source = (file) => ({ kind: "skill", name: skill.name, file, flavor });
  const files = [{ path: `${dir}/${skill.name}/SKILL.md`, content: frontmatter(data, renderPlaceholders(skill.body, manifest)), source: source("SKILL.md") }];
  for (const f of skill.files) {
    const buf = fs.readFileSync(path.join(skill.dir, f));
    const content = f.endsWith(".md") ? renderPlaceholders(buf.toString("utf8"), manifest) : buf;
    files.push({ path: `${dir}/${skill.name}/${f}`, content, source: source(f) });
  }
  return files;
}

// ---------------------------------------------------------------- hooks

const EDIT = "edit";
const SHELL = "shell";
const HOOK_MAP = {
  claude: {
    "session-start": ["SessionStart"],
    "prompt-submit": ["UserPromptSubmit"],
    "before-edit": ["PreToolUse", EDIT],
    "after-edit": ["PostToolUse", EDIT],
    "before-shell": ["PreToolUse", SHELL],
    "after-shell": ["PostToolUse", SHELL],
    stop: ["Stop"],
  },
};
HOOK_MAP.codex = HOOK_MAP.claude;
const MATCHERS = {
  claude: { [EDIT]: "Edit|Write|MultiEdit|NotebookEdit", [SHELL]: "Bash" },
  codex: { [EDIT]: "apply_patch|Edit|Write", [SHELL]: "Bash|exec_command" },
};

function hookConfig(system, hooks) {
  const config = {};
  for (const h of hooks) {
    const [event, kind] = HOOK_MAP[system][h.data.event];
    const command = system === "claude" ? `node "$CLAUDE_PROJECT_DIR/${BRIDGE}" claude ${h.name}` : `node ${BRIDGE} codex ${h.name}`;
    const entry = kind ? { matcher: MATCHERS[system][kind] } : {};
    entry.hooks = [{ type: "command", command, timeout: h.data.timeout || 60 }];
    (config[event] ||= []).push(entry);
  }
  return config;
}

function opencodePlugin(hooks) {
  const defs = hooks.map((h) => ({ name: h.name, event: h.data.event, blocking: Boolean(h.data.blocking), timeout: h.data.timeout || 60 }));
  return `// Generated by ${SIGNED} from .jow/hooks/ - do not edit.
// Change .jow/ then run: jo-workflow sync
import { spawnSync } from "node:child_process"

const HOOKS = ${JSON.stringify(defs, null, 2)}

const KIND = { bash: "shell", edit: "edit", patch: "edit", write: "write" }
const pending = new Map()

export const HarnessHooks = async ({ directory }) => {
  const run = (hook, payload) => {
    const r = spawnSync("node", ["${BRIDGE}", "opencode", hook.name], {
      cwd: directory,
      input: JSON.stringify({ event: hook.event, system: "opencode", ...payload }),
      encoding: "utf8",
      timeout: hook.timeout * 1000,
    })
    if (r.status === 2 && hook.blocking) throw new Error((r.stderr || "Blocked by harness hook " + hook.name).trim())
  }
  const fire = (event, payload) => {
    for (const hook of HOOKS) if (hook.event === event) run(hook, payload)
  }
  const describe = (tool, args = {}) => {
    const kind = KIND[tool]
    const files = [args.filePath, args.path].filter(Boolean)
    for (const m of String(args.patchText || "").matchAll(/\\*\\*\\* (?:Add|Update|Delete) File: (.+)/g)) files.push(m[1].trim())
    return { kind, payload: { tool: kind || tool, files, command: args.command ?? null } }
  }

  return {
    "tool.execute.before": async (input, output) => {
      const { kind, payload } = describe(input.tool, output.args)
      pending.set(input.callID, output.args)
      if (kind === "shell") fire("before-shell", payload)
      else if (kind) fire("before-edit", payload)
    },
    "tool.execute.after": async (input) => {
      const { kind, payload } = describe(input.tool, pending.get(input.callID))
      pending.delete(input.callID)
      if (kind === "shell") fire("after-shell", payload)
      else if (kind) fire("after-edit", payload)
    },
    event: async ({ event }) => {
      if (event.type === "session.created") fire("session-start", {})
      if (event.type === "session.idle") fire("stop", { stop_active: false })
    },
  }
}
`;
}

// ---------------------------------------------------------------- systems

export const CLAUDE_TOOLS = { read: ["Read"], search: ["Grep", "Glob"], edit: ["Edit"], write: ["Write"], shell: ["Bash"], web: ["WebFetch", "WebSearch"] };
const tools = (a) => (Array.isArray(a.data.tools) ? a.data.tools : []);

function renderClaude(ctx) {
  const { manifest, items, out } = ctx;
  const md = ctx.agentsMd ? `${BANNER_MD}@AGENTS.md\n` : ctx.instructions;
  out.files.push({ path: "CLAUDE.md", content: md });

  for (const s of items.skill) {
    const data = { name: s.name, description: s.data.description, "argument-hint": s.data["argument-hint"] || undefined };
    if (s.data["user-invocable"] === false) data["user-invocable"] = false;
    out.files.push(...skillFiles(s, manifest, ".claude/skills", data, "claude"));
  }
  for (const a of items.agent) {
    const t = [...new Set(tools(a).flatMap((x) => CLAUDE_TOOLS[x] || []))];
    const data = { name: a.name, description: a.data.description, tools: t.length ? t.join(", ") : undefined, model: a.data.model };
    const source = { kind: "agent", name: a.name, flavor: "claude" };
    out.files.push({ path: `.claude/agents/${a.name}.md`, content: frontmatter(data, renderPlaceholders(a.body, manifest)), source });
  }

  const allow = manifest.permissions["allow-shell"].flatMap((c) => [`Bash(${c})`, `Bash(${c} *)`]);
  const deny = manifest.permissions["deny-read"].map((p) => `Read(./${p})`);
  const hooks = hookConfig("claude", items.hook);
  out.merges.push({
    path: ".claude/settings.json",
    apply(settings, prev = {}) {
      const perms = (settings.permissions ||= {});
      const keep = (list, old) => (list || []).filter((x) => !(old || []).includes(x));
      perms.allow = [...new Set([...keep(perms.allow, prev.allow), ...allow])];
      perms.deny = [...new Set([...keep(perms.deny, prev.deny), ...deny])];
      const merged = {};
      for (const [event, entries] of Object.entries(settings.hooks || {})) {
        const mine = entries.filter((e) => !(e.hooks || []).some((h) => BRIDGE_RE.test(String(h.command || ""))));
        if (mine.length) merged[event] = mine;
      }
      for (const [event, entries] of Object.entries(hooks)) merged[event] = [...(merged[event] || []), ...entries];
      if (Object.keys(merged).length) settings.hooks = merged;
      else delete settings.hooks;
      return { value: settings, managed: { allow, deny } };
    },
  });
}

function renderOpencode(ctx) {
  const { manifest, items, out, systems } = ctx;
  for (const s of items.skill.filter((s) => s.data["user-invocable"] !== false)) {
    const data = { description: firstSentence(s.data.description) };
    const body = `Load the \`${s.name}\` skill and follow it for this request:\n\n$ARGUMENTS\n`;
    out.files.push({ path: `.opencode/commands/${s.name}.md`, content: frontmatter(data, body) });
  }
  for (const a of items.agent) {
    const t = tools(a);
    const permission = {};
    if (!t.includes("edit") && !t.includes("write")) permission.edit = "deny";
    if (!t.includes("shell")) permission.bash = "deny";
    if (!t.includes("web")) permission.webfetch = "deny";
    const data = { description: a.data.description, mode: "subagent", permission: Object.keys(permission).length ? permission : undefined };
    const source = { kind: "agent", name: a.name, flavor: "opencode" };
    out.files.push({ path: `.opencode/agents/${a.name}.md`, content: frontmatter(data, renderPlaceholders(a.body, manifest)), source });
  }
  const hooks = items.hook.filter((h) => {
    if (h.data.event !== "prompt-submit") return true;
    out.warnings.push(`opencode: hook '${h.name}' skipped (no prompt-submit event in OpenCode plugins)`);
    return false;
  });
  if (hooks.length) out.files.push({ path: ".opencode/plugins/jow-hooks.js", content: opencodePlugin(hooks) });
  // OpenCode reads both .claude/skills and .agents/skills: no copy of its own needed.
  if (!systems.includes("claude")) ctx.needAgentsSkills = true;

  const bashAllow = Object.fromEntries(manifest.permissions["allow-shell"].map((c) => [`${c}*`, "allow"]));
  const readDeny = Object.fromEntries(manifest.permissions["deny-read"].map((p) => [p, "deny"]));
  out.merges.push({
    path: "opencode.json",
    apply(config, prev = {}) {
      config.$schema ||= "https://opencode.ai/config.json";
      const perm = (config.permission ||= {});
      const patch = (key, add, old = []) => {
        const cur = typeof perm[key] === "string" ? { "*": perm[key] } : { ...(perm[key] || {}) };
        for (const k of old) delete cur[k];
        // "*" first: in OpenCode the last matching rule wins.
        const { "*": star, ...rest } = cur;
        perm[key] = { "*": star ?? (key === "bash" ? "ask" : "allow"), ...rest, ...add };
      };
      patch("bash", bashAllow, prev.bash);
      patch("read", readDeny, prev.read);
      return { value: config, managed: { bash: Object.keys(bashAllow), read: Object.keys(readDeny) } };
    },
  });
}

const tomlString = (s) => JSON.stringify(String(s));
const tomlMultiline = (s) => `'''\n${s.replace(/'''/g, "'\"'\"'")}'''`;

function renderCodex(ctx) {
  const { manifest, items, out } = ctx;
  ctx.needAgentsSkills = true;
  for (const a of items.agent) {
    const t = tools(a);
    const lines = [
      `# Generated by ${SIGNED} from .jow/agents/ - do not edit.`,
      `name = ${tomlString(a.name)}`,
      `description = ${tomlString(a.data.description)}`,
    ];
    if (!t.includes("edit") && !t.includes("write")) lines.push('sandbox_mode = "read-only"');
    lines.push(`developer_instructions = ${tomlMultiline(renderPlaceholders(a.body, manifest).trim() + "\n")}`);
    const source = { kind: "agent", name: a.name, flavor: "codex" };
    out.files.push({ path: `.codex/agents/${a.name}.toml`, content: lines.join("\n") + "\n", source });
  }
  out.files.push({
    path: ".codex/config.toml",
    content: [
      `# Generated by ${SIGNED} - do not edit. Applied only when the project is trusted.`,
      'approval_policy = "on-request"',
      'sandbox_mode = "workspace-write"',
      "",
      "[sandbox_workspace_write]",
      "network_access = false",
      "",
    ].join("\n"),
  });
  if (items.hook.length) out.files.push({ path: ".codex/hooks.json", content: json({ hooks: hookConfig("codex", items.hook) }) });
}

// ---------------------------------------------------------------- entry

export function renderAll(manifest, items) {
  const systems = manifest.systems;
  manifest = { ...manifest, placeholders: extraPlaceholders(manifest, items) };
  const out = { files: [], merges: [], warnings: [] };
  const ctx = { manifest, items, out, systems, instructions: instructions(manifest, items, systems) };
  ctx.agentsMd = systems.includes("codex") || systems.includes("opencode");

  for (const f of walk(path.join(GENERATOR_ROOT, "runtime"))) {
    out.files.push({ path: `.jow/runtime/${f}`, content: read(path.join(GENERATOR_ROOT, "runtime", f)) });
  }
  if (ctx.agentsMd) out.files.push({ path: "AGENTS.md", content: ctx.instructions });
  if (systems.includes("claude")) renderClaude(ctx);
  if (systems.includes("opencode")) renderOpencode(ctx);
  if (systems.includes("codex")) renderCodex(ctx);
  if (ctx.needAgentsSkills) {
    for (const s of items.skill) out.files.push(...skillFiles(s, manifest, ".agents/skills", { name: s.name, description: s.data.description }, "agents"));
  }
  return out;
}
